def get_lang() -> str:
    try:
        from config_manager import config_mgr
        lang = str(getattr(config_mgr.config, "language", "zh") or "zh").lower()
        return "en" if lang.startswith("en") else "zh"
    except Exception:
        return "zh"


def tr(key: str, lang: str | None = None, **kwargs: Any) -> str:
    active_lang = "en" if (lang or get_lang()).startswith("en") else "zh"
    table = TRANSLATIONS.get(active_lang, TRANSLATIONS["zh"])
    template = table.get(key) or TRANSLATIONS["zh"].get(key) or key
    if kwargs:
        try:
            return template.format(**kwargs)
        except Exception:
            return template
    return template
